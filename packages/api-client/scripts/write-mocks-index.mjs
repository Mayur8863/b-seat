// Writes src/generated/mocks.ts re-exporting every generated MSW handler file.
import { readdirSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = new URL('../src/generated/', import.meta.url).pathname;

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory() ? walk(join(dir, entry.name)) : [join(dir, entry.name)],
  );
}

const files = walk(join(root, 'endpoints'))
  .filter((file) => file.endsWith('.msw.ts'))
  .sort()
  .map((file) => `export * from './${relative(root, file).replace(/\.ts$/, '')}';`);

writeFileSync(
  join(root, 'mocks.ts'),
  `// Generated by scripts/write-mocks-index.mjs. Do not edit.\n${files.join('\n')}\n`,
);
