import { sql } from 'drizzle-orm';
import {
  check,
  index,
  integer,
  pgTable,
  smallint,
  text,
  timestamp,
  unique,
  uuid,
} from 'drizzle-orm/pg-core';

import { space } from './space.js';

export const PHOTO_PURGE_REASONS = ['deleted', 'abandoned_upload'] as const;

/**
 * One fully added photo of one space (ADR-0011). Position 1 is the cover.
 * The unique is made DEFERRABLE INITIALLY IMMEDIATE by a custom migration (drizzle-kit cannot
 * express it), so a single permuting UPDATE is checked at statement end.
 */
export const spacePhoto = pgTable(
  'space_photo',
  {
    // Generated by the API before the objects are written: it is part of the storage keys.
    id: uuid().primaryKey().defaultRandom(),
    spaceId: uuid()
      .notNull()
      .references(() => space.id, { onDelete: 'restrict' }),
    position: smallint().notNull(),
    description: text(),
    displayWidth: integer().notNull(),
    displayHeight: integer().notNull(),
    createdAt: timestamp({ withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp({ withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    check('space_photo_position_range', sql`${t.position} BETWEEN 1 AND 10`),
    unique('space_photo_position_unique').on(t.spaceId, t.position),
    check(
      'space_photo_description_length',
      sql`${t.description} IS NULL OR char_length(${t.description}) BETWEEN 1 AND 150`,
    ),
    check(
      'space_photo_display_size_positive',
      sql`${t.displayWidth} > 0 AND ${t.displayHeight} > 0`,
    ),
  ],
);

/** Outbox of storage objects to delete; it outlives the photo row, so no foreign keys. */
export const photoObjectPurge = pgTable(
  'photo_object_purge',
  {
    id: uuid().primaryKey().defaultRandom(),
    spaceId: uuid().notNull(),
    photoId: uuid().notNull(),
    reason: text().notNull(),
    dueAt: timestamp({ withTimezone: true }).notNull(),
    attempts: integer().notNull().default(0),
    // Set by the sweep claim; doubles as the 10-minute lease.
    lastAttemptAt: timestamp({ withTimezone: true }),
    createdAt: timestamp({ withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    check('photo_object_purge_reason_valid', sql`${t.reason} IN ('deleted', 'abandoned_upload')`),
    check('photo_object_purge_attempts_nonnegative', sql`${t.attempts} >= 0`),
    unique('photo_object_purge_photo_id_unique').on(t.photoId),
    index('photo_object_purge_due_idx').on(t.dueAt),
  ],
);
